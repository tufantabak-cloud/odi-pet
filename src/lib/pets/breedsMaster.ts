/**
 * Kullanıcı girdisiyle ırk araması yapar (Türkçe karakter toleranslı, alias duyarlı, case-insensitive, alfabe sırasına göre).
 */
export function searchBreeds(query: string, species?: 'cat' | 'dog' | string): BreedItem[] {
  const normSpec = species === 'cat' || species === 'kedi' ? 'cat' : species === 'dog' || species === 'köpek' || species === 'kopek' ? 'dog' : null;
  const list = normSpec ? (normSpec === 'cat' ? CAT_BREEDS_MASTER : DOG_BREEDS_MASTER) : MASTER_BREEDS;

  const rawNorm = normalizeText(query);
  const filtered = !rawNorm
    ? list
    : list.filter((item) => {
        if (normalizeText(item.name).includes(rawNorm)) return true;
        if (normalizeText(item.name_tr).includes(rawNorm)) return true;
        if (normalizeText(item.name_en).includes(rawNorm)) return true;
        if (normalizeText(item.id).includes(rawNorm)) return true;
        return item.aliases.some((alias) => normalizeText(alias).includes(rawNorm));
      });

  return [...filtered].sort((a, b) => a.name.localeCompare(b.name, 'tr'));
}

/**
 * Herhangi bir string (id, name, name_tr, name_en veya alias) üzerinden eşleşen BreedItem nesnesini bulur.
 */
export function findBreedByIdOrName(
  rawBreed: string | null | undefined,
  species?: 'cat' | 'dog' | string
): BreedItem | null {
  if (!rawBreed) return null;

  const normSpec = species === 'cat' || species === 'kedi' ? 'cat' : species === 'dog' || species === 'köpek' || species === 'kopek' ? 'dog' : null;
  const list = normSpec ? (normSpec === 'cat' ? CAT_BREEDS_MASTER : DOG_BREEDS_MASTER) : MASTER_BREEDS;

  const norm = normalizeText(rawBreed);
  if (!norm) return null;

  // 1. Tam ID eşleşmesi
  let matched = list.find((b) => b.id === rawBreed || normalizeText(b.id) === norm);
  if (matched) return matched;

  // 2. Tam isim eşleşmesi (name, name_tr, name_en)
  matched = list.find(
    (b) =>
      normalizeText(b.name) === norm ||
      normalizeText(b.name_tr) === norm ||
      normalizeText(b.name_en) === norm
  );
  if (matched) return matched;

  // 3. Tam alias eşleşmesi
  matched = list.find((b) => b.aliases.some((alias) => normalizeText(alias) === norm));
  if (matched) return matched;

  // 4. İsim içinde başlayan / geçen kısmi eşleşme
  matched = list.find(
    (b) =>
      normalizeText(b.name).includes(norm) ||
      normalizeText(b.name_tr).includes(norm) ||
      normalizeText(b.name_en).includes(norm)
  );
  if (matched) return matched;

  // 5. Alias içinde geçen kısmi eşleşme
  matched = list.find((b) => b.aliases.some((alias) => normalizeText(alias).includes(norm)));

  return matched || null;
}

/**
 * Geriye dönük uyumlulukla, ham ırk metnini veya ID'yi temiz kullanıcı adı olarak döndürür.
 * Veritabanındaki eski metinler bozulmaz, sistem bilinen eşleşme varsa güzelleştirir.
 */
export function resolveBreedDisplayName(
  rawBreed: string | null | undefined,
  species?: 'cat' | 'dog' | string
): string {
  if (!rawBreed || !rawBreed.trim()) return 'Bilinmiyor';
  const found = findBreedByIdOrName(rawBreed, species);
  if (found) return found.name;
  return rawBreed.trim();
}
