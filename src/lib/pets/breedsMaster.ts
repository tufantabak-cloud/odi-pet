export interface BreedItem {
  id: string;
  species: 'cat' | 'dog';
  name: string;
  name_tr: string;
  name_en: string;
  aliases: string[];
  category: 'purebred' | 'mixed' | 'designer' | 'local_variant';
  is_mixed: boolean;
  is_recognized_breed: boolean;
  recognitionSources?: string[];
  popular?: boolean;
  status: 'active' | 'deprecated';
}

/**
 * Türkçe karakter ve özel sembol temizleme / normalizasyon yardımcı fonksiyonu.
 */
export function normalizeText(text: string): string {
  if (!text) return '';
  return text
    .toLowerCase()
    .replace(/ğ/g, 'g')
    .replace(/ü/g, 'u')
    .replace(/ş/g, 's')
    .replace(/ı/g, 'i')
    .replace(/ö/g, 'o')
    .replace(/ç/g, 'c')
    .replace(/İ/g, 'i')
    .replace(/I/g, 'i')
    .replace(/[^a-z0-9\s]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

